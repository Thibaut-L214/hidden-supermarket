"""Layout of the store's printed atlas: fictitious packaging, shelf-edge labels, posters.

One 2048² colour image (blender/textures/pack_color.jpg) and its normal map, generated by
make_store_textures.py and bound to the material M_PACK_ATLAS by scripts/lib/surfaces.mjs
(`atlases` in blender/textures/surfaces.json). The builders author the UVs themselves
(store_props.py, `UVAuthored` layer), so this module is the single place that knows where each
design sits. Nothing printed here imitates a real brand: colour bands, plain shapes, bars that
stand for text, generic pictograms.

Rectangles are (x0, y0, x1, y1) in pixels, origin at the bottom-left corner like UV space.

  y 1536-2048  four posters (448 × 512), then a 256-wide column: shelf-edge label cells,
               carton labels, tray labels, plain swatches
  y 0-1536     six rows of ten product blocks (192 × 256)

A product block holds every face of one design:
  boxes      front 128 × 208 | side 64 × 208, and above them a 192 × 48 strip for the top
             (several packs deep: the strip runs from the shelf front to the back)
  cylinders  wrap 192 × 208 (u around, seam at the back; v along the height), and above it
             four lids seen from above (the first one maps the cap, the row maps the fill behind)
"""

from __future__ import annotations

SIZE = 2048
BLOCK_W, BLOCK_H, TOP_H = 192, 256, 48
FRONT_W = 128
COLUMNS = 10
MATERIAL = "M_PACK_ATLAS"

# kind → (number of designs, cylinder?, physical front or wrap size in metres (w, h)).
KINDS = {
    "box": (8, False, (0.2, 0.24)),
    "tall_box": (8, False, (0.19, 0.35)),
    "bag": (6, False, (0.17, 0.29)),
    "brick": (8, False, (0.09, 0.21)),
    "bottle": (10, True, (0.283, 0.32)),
    "jar": (6, True, (0.346, 0.15)),
    "can": (8, True, (0.251, 0.12)),
    "pot": (6, True, (0.283, 0.09)),
}

Rect = tuple[float, float, float, float]


def variants(kind: str) -> int:
    return KINDS[kind][0]


def _first(kind: str) -> int:
    index = 0
    for name, (count, _, _) in KINDS.items():
        if name == kind:
            return index
        index += count
    raise KeyError(kind)


def block(kind: str, variant: int) -> dict[str, Rect]:
    """Pixel rectangles of one product design."""
    index = _first(kind) + variant % variants(kind)
    x0, y0 = (index % COLUMNS) * BLOCK_W, (index // COLUMNS) * BLOCK_H
    body = y0 + BLOCK_H - TOP_H
    rects = {"top": (x0, body, x0 + BLOCK_W, y0 + BLOCK_H)}
    if KINDS[kind][1]:
        rects["wrap"] = (x0, y0, x0 + BLOCK_W, body)
        rects["cap"] = (x0, body, x0 + TOP_H, y0 + BLOCK_H)
    else:
        rects["front"] = (x0, y0, x0 + FRONT_W, body)
        rects["side"] = (x0 + FRONT_W, y0, x0 + BLOCK_W, body)
    return rects


POSTER_W, POSTER_H, POSTERS = 448, 512, 4
_TOP = 6 * BLOCK_H  # 1536
_COL = POSTERS * POSTER_W  # 1792
RAILS, CARTON_LABELS, TRAY_LABELS = 4, 2, 2
SWATCHES = ("rail", "white", "dark", "liner")


def poster(i: int) -> Rect:
    x0 = (i % POSTERS) * POSTER_W
    return (x0, _TOP, x0 + POSTER_W, _TOP + POSTER_H)


def rail(i: int) -> Rect:
    """Shelf-edge cell: 24 cm of rail with one label."""
    y0 = _TOP + (i % RAILS) * 64
    return (_COL, y0, _COL + 256, y0 + 64)


def carton_label(i: int) -> Rect:
    y0 = _TOP + 256 + (i % CARTON_LABELS) * 64
    return (_COL, y0, _COL + 256, y0 + 64)


def tray_label(i: int) -> Rect:
    x0 = _COL + (i % TRAY_LABELS) * 128
    return (x0, _TOP + 384, x0 + 128, _TOP + 448)


def swatch(name: str) -> Rect:
    x0 = _COL + SWATCHES.index(name) * 64
    return (x0, _TOP + 448, x0 + 64, _TOP + 512)


def uv(rect: Rect, inset: float = 2.0) -> Rect:
    """Normalised (u0, v0, u1, v1), pulled in by `inset` pixels against bleeding between cells."""
    x0, y0, x1, y1 = rect
    return ((x0 + inset) / SIZE, (y0 + inset) / SIZE, (x1 - inset) / SIZE, (y1 - inset) / SIZE)
